from PIL import Image
import torch


def kerasense_predict(
    map_paths,
    model=binary_model,
    threshold=0.50
):
    """
    Predict Keratoconus vs Non-Keratoconus
    from seven corneal maps.

    map_paths must follow MAP_TYPES order:
    [Sag_A, Sag_P, Elv_A, Elv_P,
     CT_A, EC_A, EC_P]
    """

    if len(map_paths) != 7:
        raise ValueError(
            "KeraSense requires exactly 7 corneal maps."
        )

    model.eval()

    processed_maps = []

    for image_path in map_paths:

        image = Image.open(
            image_path
        ).convert("RGB")

        image = val_transform(
            image
        )

        processed_maps.append(
            image
        )

    # 7 × C × H × W
    maps_tensor = torch.stack(
        processed_maps
    )

    # 1 × 7 × C × H × W
    maps_tensor = maps_tensor.unsqueeze(0)

    maps_tensor = maps_tensor.to(device)

    with torch.no_grad():

        outputs = model(
            maps_tensor
        )

        probabilities = torch.softmax(
            outputs,
            dim=1
        )

        kc_probability = (
            probabilities[0, 1]
            .item()
        )

    prediction = (
        "Keratoconus"
        if kc_probability >= threshold
        else "Non-Keratoconus"
    )

    return {
        "prediction": prediction,
        "kc_probability": kc_probability,
        "non_kc_probability": (
            1.0 - kc_probability
        ),
        "threshold": threshold,
        "maps_analyzed": 7,
        "map_types": MAP_TYPES
    }


