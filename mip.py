class BinaryKeraSenseModel(nn.Module):

    def __init__(self):
        super().__init__()

        # Shared EfficientNet-B0 backbone
        self.backbone = efficientnet_b0(
            weights=EfficientNet_B0_Weights.DEFAULT
        )

        feature_dim = self.backbone.classifier[1].in_features

        # Remove original ImageNet classifier
        self.backbone.classifier = nn.Identity()

        # 7-map multimodal fusion
        self.fusion = nn.Sequential(

            nn.Linear(
                feature_dim * 7,
                512
            ),

            nn.ReLU(),

            nn.Dropout(0.3),

            nn.Linear(
                512,
                128
            ),

            nn.ReLU(),

            nn.Dropout(0.2),

            # Binary output
            nn.Linear(
                128,
                2
            )
        )

    def forward(self, x):

        features = []

        # Extract features from all 7 corneal maps
        for i in range(7):

            feature = self.backbone(
                x[:, i, :, :, :]
            )

            features.append(feature)

        # Fuse all seven representations
        fused_features = torch.cat(
            features,
            dim=1
        )

        return self.fusion(
            fused_features
        )


